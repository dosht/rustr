#!/usr/bin/env python3
"""Generate shell colors from design-tokens.json; --check is read-only.

Run from any directory. Output is UTF-8 with LF endings, no timestamps. Change
only the root JSON, then regenerate and commit the outputs together. Contrast
checks cover normal text (4.5:1) and control boundaries/focus rings (3:1).
"""

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
TOKENS = (
    "bg", "surface", "fg", "muted", "border", "accent", "accent-hover",
    "on-accent", "cursor-bg", "notice-bg", "error", "error-bg", "on-error", "focus",
    "success", "progress",
)
MODES = ("light", "dark")
HEADER = "Generated by scripts/gen-tokens.py from design-tokens.json. Do not edit."


def luminance(value):
    channels = [int(value[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return sum(c * w for c, w in zip(linear, (0.2126, 0.7152, 0.0722)))


def contrast(a, b):
    lo, hi = sorted((luminance(a), luminance(b)))
    return (hi + 0.05) / (lo + 0.05)


def load_tokens():
    data = json.loads((ROOT / "design-tokens.json").read_text(encoding="utf-8"))
    if data.get("version") != 1 or len(data.get("palettes", [])) != 3:
        raise ValueError("expected version 1 and exactly three E3 palettes")
    ids = set()
    for palette in data["palettes"]:
        name = palette.get("id", "")
        if not re.fullmatch(r"[a-z]+(?:-[a-z]+)*", name) or name in ids:
            raise ValueError(f"invalid or duplicate palette id: {name!r}")
        ids.add(name)
        if not isinstance(palette.get("name"), str) or not palette["name"].strip():
            raise ValueError(f"{name}: display name is required")
        for mode in MODES:
            colors = palette.get(mode, {})
            if set(colors) != set(TOKENS):
                raise ValueError(f"{name}/{mode}: expected exactly {', '.join(TOKENS)}")
            if any(not isinstance(c, str) or not re.fullmatch(r"#[0-9a-f]{6}", c) for c in colors.values()):
                raise ValueError(f"{name}/{mode}: colors must be lowercase #rrggbb")
            pairs = [(fg, bg, 4.5) for fg in ("fg", "muted", "accent", "success", "progress")
                     for bg in ("bg", "surface", "cursor-bg", "notice-bg")]
            pairs += [("on-accent", "accent", 4.5), ("on-accent", "accent-hover", 4.5),
                      ("accent-hover", "bg", 4.5), ("error", "error-bg", 4.5),
                      ("error", "bg", 4.5), ("error", "surface", 4.5), ("on-error", "error", 4.5)]
            pairs += [(fg, bg, 3) for fg in ("border", "focus") for bg in ("bg", "surface")]
            for fg, bg, minimum in pairs:
                ratio = contrast(colors[fg], colors[bg])
                if ratio < minimum:
                    raise ValueError(f"{name}/{mode}: {fg} on {bg} contrast {ratio:.2f} < {minimum}")
    if data.get("defaultPalette") != data["palettes"][0]["id"]:
        raise ValueError("the first E3 palette must remain default until mu selects")
    return data


def camel(value):
    first, *rest = value.split("-")
    return first + "".join(word.title() for word in rest)


def css(data):
    blocks = [f"/* {HEADER} */"]
    for palette in data["palettes"]:
        selectors = [f'[data-palette="{palette["id"]}"]']
        if palette["id"] == data["defaultPalette"]:
            selectors.insert(0, ":root:not([data-palette])")

        def block(selectors, mode):
            lines = [",\n".join(selectors) + " {", f"  color-scheme: {mode};"]
            lines += [f"  --{key}: {palette[mode][key]};" for key in TOKENS]
            return "\n".join(lines + ["}"])

        blocks.append(block(selectors, "light"))
        system = block([s + ':not([data-theme="light"])' for s in selectors], "dark")
        blocks.append("@media (prefers-color-scheme: dark) {\n" +
                      "\n".join("  " + line for line in system.splitlines()) + "\n}")
        blocks.append(block([s + '[data-theme="dark"]' for s in selectors], "dark"))
    return "\n\n".join(blocks) + "\n"


def typescript(data):
    palettes = [{"id": p["id"], "name": p["name"]} for p in data["palettes"]]
    return (f"// {HEADER}\n"
            f"export const palettes = {json.dumps(palettes, indent=2)} as const;\n"
            f"export const defaultPalette = {json.dumps(data['defaultPalette'])};\n"
            'export const modes = ["light", "dark"] as const;\n')


def kotlin(data):
    roles = {
        "primary": "accent", "onPrimary": "on-accent", "primaryContainer": "cursor-bg", "onPrimaryContainer": "fg",
        "secondary": "accent", "onSecondary": "on-accent", "secondaryContainer": "notice-bg", "onSecondaryContainer": "fg",
        "tertiary": "accent", "onTertiary": "on-accent", "tertiaryContainer": "cursor-bg", "onTertiaryContainer": "fg",
        "background": "bg", "onBackground": "fg", "surface": "bg", "onSurface": "fg",
        "surfaceVariant": "surface", "onSurfaceVariant": "muted", "surfaceTint": "accent",
        "inverseSurface": "fg", "inverseOnSurface": "bg", "error": "error", "onError": "on-error",
        "errorContainer": "error-bg", "onErrorContainer": "error", "outline": "border", "outlineVariant": "border",
        "scrim": "fg", "surfaceBright": "surface", "surfaceDim": "bg", "surfaceContainer": "surface",
        "surfaceContainerHigh": "surface", "surfaceContainerHighest": "surface",
        "surfaceContainerLow": "bg", "surfaceContainerLowest": "bg",
    }
    lines = [f"// {HEADER}", "package dev.taskr.android.ui", "",
             "import androidx.compose.material3.ColorScheme", "import androidx.compose.material3.darkColorScheme",
             "import androidx.compose.material3.lightColorScheme", "import androidx.compose.ui.graphics.Color", "",
             "object DesignTokens {", f'    const val defaultPalette = "{data["defaultPalette"]}"']
    for p in data["palettes"]:
        for mode in MODES:
            lines += [f"    private val {camel(p['id'])}{mode.title()} by lazy {{",
                      f"        {mode}ColorScheme("]
            lines += [f"            {role} = Color(0xff{p[mode][token][1:]})," for role, token in roles.items()]
            opposite = "dark" if mode == "light" else "light"
            lines.append(f"            inversePrimary = Color(0xff{p[opposite]['accent'][1:]}),")
            lines += ["        )", "    }"]
    lines += ["", "    fun colors(dark: Boolean, palette: String = defaultPalette): ColorScheme = when (palette) {"]
    for p in data["palettes"]:
        name = camel(p["id"])
        lines.append(f'        "{p["id"]}" -> if (dark) {name}Dark else {name}Light')
    lines += ['        else -> error("Unknown palette: $palette")', "    }", "}"]
    return "\n".join(lines) + "\n"


def swift(data):
    lines = [f"// {HEADER}", "import SwiftUI", "import UIKit", "", "struct TaskrColors {"]
    lines += [f"    let {camel(key)}: Color" for key in TOKENS]
    lines += ["}", "", "enum DesignTokens {"]
    for p in data["palettes"]:
        lines.append(f"    static let {camel(p['id'])} = TaskrColors(")
        for index, key in enumerate(TOKENS):
            comma = "," if index < len(TOKENS) - 1 else ""
            lines.append(f"        {camel(key)}: adaptive(0x{p['light'][key][1:]}, 0x{p['dark'][key][1:]}){comma}")
        lines.append("    )")
    lines += [f"    static let current = {camel(data['defaultPalette'])}", "",
              "    private static func adaptive(_ light: UInt32, _ dark: UInt32) -> Color {",
              "        Color(uiColor: UIColor { traits in",
              "            let rgb = traits.userInterfaceStyle == .dark ? dark : light",
              "            return UIColor(red: CGFloat((rgb >> 16) & 255) / 255,",
              "                           green: CGFloat((rgb >> 8) & 255) / 255,",
              "                           blue: CGFloat(rgb & 255) / 255, alpha: 1)",
              "        })", "    }", "}"]
    return "\n".join(lines) + "\n"


def rust(data):
    lines = [f"// {HEADER}", "// All E3 alternatives are generated; the TUI keeps its existing dark default.",
             "#![allow(dead_code)]", "use ratatui::style::Color;", "", "pub struct Tokens {"]
    lines += [f"    pub {key.replace('-', '_')}: Color," for key in TOKENS]
    lines += ["}", ""]
    for p in data["palettes"]:
        for mode in MODES:
            lines.append(f"pub const {p['id'].replace('-', '_').upper()}_{mode.upper()}: Tokens = Tokens {{")
            for key in TOKENS:
                color = p[mode][key]
                rgb = ", ".join("0x" + color[i:i + 2] for i in (1, 3, 5))
                lines.append(f"    {key.replace('-', '_')}: Color::Rgb({rgb}),")
            lines += ["};", ""]
    default = data["defaultPalette"].replace("-", "_").upper()
    lines += [f"pub const DEFAULT_LIGHT: Tokens = {default}_LIGHT;", f"pub const DEFAULT_DARK: Tokens = {default}_DARK;"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report missing/stale outputs without writing")
    args = parser.parse_args()
    try:
        data = load_tokens()
        outputs = {
            "apps/web/src/tokens.css": css(data),
            "apps/web/src/lib/theme/palettes.ts": typescript(data),
            "apps/android/app/src/main/java/dev/taskr/android/ui/DesignTokens.kt": kotlin(data),
            "apps/ios/Taskr/DesignTokens.swift": swift(data),
            "crates/taskr-tui/src/design_tokens.rs": rust(data),
            "transgate/web/src/tokens.css": css(data),
            "transgate/web/src/lib/theme/palettes.ts": typescript(data),
        }
        stale = []
        for name, content in outputs.items():
            path = ROOT / name
            encoded = content.encode("utf-8")
            if path.exists() and path.read_bytes() == encoded:
                continue
            stale.append(name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(encoded)
        if args.check and stale:
            print("Token outputs missing or stale:\n" + "\n".join(stale), file=sys.stderr)
            return 1
        action = "checked" if args.check else "generated"
        print(f"{action} {len(outputs)} token outputs from 3 palettes x 2 modes; contrast checks passed")
        return 0
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"gen-tokens: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
