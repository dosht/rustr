-- Transgate jobs, transcripts, provider attempts, durable callback intake,
-- privacy settings, retention runs, account erasure and shared rate limits.
-- History lives in transgate_jobs._sqlx_migrations. Run after the billing
-- migrations: the billing_runtime role must already exist, and a running
-- server acts as it (one verified pool, one host transaction with billing).

CREATE FUNCTION transgate_jobs.us_to_ts(us bigint) RETURNS timestamptz
  LANGUAGE sql IMMUTABLE STRICT AS $$ SELECT to_timestamp(0) + us * interval '1 microsecond' $$;
CREATE FUNCTION transgate_jobs.ts_to_us(ts timestamptz) RETURNS bigint
  LANGUAGE sql IMMUTABLE STRICT AS $$ SELECT (extract(epoch FROM ts - to_timestamp(0)) * 1000000)::bigint $$;

-- Job and line ids keep the source's signed database ids, so imported rows
-- keep theirs (BY DEFAULT).
CREATE TABLE transgate_jobs.jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id uuid NOT NULL,
  revision bigint NOT NULL DEFAULT 1,
  status text NOT NULL CHECK (status IN ('draft', 'not_started', 'pending', 'running', 'completed', 'failed',
                                         'canceled', 'deleted', 'speaker_labeling', 'uploaded', 'processing', 'ready')),
  job_name text,
  source jsonb NOT NULL,
  language text,
  translate_to text[] NOT NULL DEFAULT '{}',
  speakers boolean NOT NULL DEFAULT false,
  fix_grammer boolean,
  duration_minutes integer,
  size_bytes bigint,
  provider text CHECK (provider IN ('runpod', 'deepgram', 'soniox', 'soniox_v5')),
  model text,
  callback_url text,
  whisper_params jsonb,
  error jsonb,
  retry_count integer NOT NULL DEFAULT 0,
  recovery_attempts integer NOT NULL DEFAULT 0,
  soniox_transcription_id text,
  started_at timestamptz,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  current_attempt uuid,
  attempts_made integer NOT NULL DEFAULT 0,
  deferred_charge text NOT NULL DEFAULT 'none'
    CHECK (deferred_charge IN ('none', 'pending', 'charged', 'refused', 'no_duration')),
  next_dispatch_at timestamptz
);

CREATE INDEX jobs_account ON transgate_jobs.jobs (account_id, id DESC);
CREATE INDEX jobs_dispatch ON transgate_jobs.jobs (next_dispatch_at) WHERE status IN ('not_started', 'pending');
CREATE INDEX jobs_running ON transgate_jobs.jobs (started_at) WHERE status = 'running';

-- Attempts outlive a hard-deleted draft and a superseded claim: their remote
-- identities are what erasure and remote cleanup must still reach.
CREATE TABLE transgate_jobs.attempts (
  id uuid PRIMARY KEY,
  job_id bigint NOT NULL,
  account_id uuid NOT NULL,
  number integer NOT NULL,
  provider text NOT NULL CHECK (provider IN ('runpod', 'deepgram', 'soniox', 'soniox_v5')),
  project text NOT NULL,
  model text NOT NULL,
  state text NOT NULL CHECK (state IN ('claimed', 'accepted', 'uncertain', 'rate_limited', 'rejected',
                                       'unavailable', 'finished', 'superseded')),
  claimed_at timestamptz NOT NULL,
  lease_until timestamptz NOT NULL,
  request jsonb NOT NULL,
  callback_secret text NOT NULL,
  remote_id text,
  accepted_at timestamptz,
  last_error jsonb,
  remote_cleanup jsonb NOT NULL,
  UNIQUE (job_id, number)
);

CREATE INDEX attempts_account ON transgate_jobs.attempts (account_id);
CREATE INDEX attempts_unresolved ON transgate_jobs.attempts (claimed_at) WHERE state IN ('claimed', 'uncertain');
CREATE INDEX attempts_cleanup ON transgate_jobs.attempts ((remote_cleanup ->> 'state'));

CREATE TABLE transgate_jobs.lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id bigint NOT NULL REFERENCES transgate_jobs.jobs (id) ON DELETE RESTRICT,
  account_id uuid NOT NULL,
  start_time text NOT NULL,
  end_time text NOT NULL,
  line text NOT NULL,
  speaker text,
  corrected_text text,
  split_on_speaker_change boolean,
  language text,
  translation_status text CHECK (translation_status IN ('original', 'translation')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX lines_job ON transgate_jobs.lines (job_id, start_time COLLATE "C", id);
CREATE INDEX lines_account ON transgate_jobs.lines (account_id);

-- Durable callback intake (C-6): one row per attempt and remote id. The raw
-- body is reduced to identity and reported duration once settled.
CREATE TABLE transgate_jobs.inbox (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  attempt_id uuid NOT NULL,
  job_id bigint NOT NULL,
  account_id uuid NOT NULL,
  remote_id text NOT NULL,
  origin text NOT NULL CHECK (origin IN ('Webhook', 'RecoveryPoll')),
  observation jsonb NOT NULL,
  fingerprint text NOT NULL,
  received_at timestamptz NOT NULL,
  state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'applied', 'conflict', 'ignored')),
  settled_at timestamptz,
  note text,
  failures integer NOT NULL DEFAULT 0,
  last_error text,
  UNIQUE (attempt_id, remote_id)
);

CREATE INDEX inbox_pending ON transgate_jobs.inbox (id) WHERE state = 'pending';
CREATE INDEX inbox_account ON transgate_jobs.inbox (account_id);

-- Job events, written in the transaction of the transition (outbox).
CREATE TABLE transgate_jobs.events (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  account_id uuid NOT NULL,
  event jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  attempts integer NOT NULL DEFAULT 0,
  claim_token uuid,
  claimed_until timestamptz,
  published_at timestamptz,
  last_error text
);

CREATE INDEX events_unpublished ON transgate_jobs.events (id) WHERE published_at IS NULL;
CREATE INDEX events_account ON transgate_jobs.events (account_id);

-- PRV-013: only the two user flags are runtime-writable; the operator fields
-- stay read-only to the server (C6).
CREATE TABLE transgate_jobs.settings (
  account_id uuid PRIMARY KEY,
  auto_delete_transcripts boolean NOT NULL DEFAULT true,
  unlimited_history boolean NOT NULL DEFAULT false,
  blocked boolean,
  deleted_monthly boolean NOT NULL DEFAULT true
);

-- PRV-021 with the two statuses the source's CHECK rejected (C10).
CREATE TABLE transgate_jobs.retention_runs (
  id uuid PRIMARY KEY,
  job_name text NOT NULL,
  table_name text NOT NULL,
  retention_days integer NOT NULL,
  cutoff timestamptz NOT NULL,
  rows_deleted bigint NOT NULL,
  execution_time_ms bigint NOT NULL,
  status text NOT NULL CHECK (status IN ('running', 'success', 'failure', 'partial', 'skipped', 'aborted')),
  error_message text,
  users_opted_out_count bigint,
  executed_at timestamptz NOT NULL,
  executed_by text NOT NULL
);

-- Owned by the account, not the job: a draft deleted after its upload URL was
-- issued still needs the re-sweep once the URL expires.
CREATE TABLE transgate_jobs.issued_uploads (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  job_id bigint NOT NULL,
  account_id uuid NOT NULL,
  object jsonb NOT NULL,
  expires_at timestamptz NOT NULL
);

CREATE INDEX issued_uploads_account ON transgate_jobs.issued_uploads (account_id);

CREATE TABLE transgate_jobs.archived_payloads (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  job_id bigint NOT NULL,
  account_id uuid NOT NULL,
  object jsonb NOT NULL
);

CREATE INDEX archived_payloads_account ON transgate_jobs.archived_payloads (account_id);

-- The host barrier and saga record (C-11, D9). It is never deleted.
CREATE TABLE transgate_jobs.erasures (
  id uuid PRIMARY KEY,
  account_id uuid NOT NULL UNIQUE,
  requested_at timestamptz NOT NULL,
  state text NOT NULL CHECK (state IN ('requested', 'local_erased', 'fully_erased', 'erased_with_exceptions')),
  local_erased_at timestamptz,
  identity_deleted_at timestamptz,
  closed_at timestamptz
);

CREATE TABLE transgate_jobs.erasure_items (
  id uuid PRIMARY KEY,
  seq bigint GENERATED ALWAYS AS IDENTITY,
  erasure_id uuid NOT NULL REFERENCES transgate_jobs.erasures (id),
  target jsonb NOT NULL,
  state jsonb NOT NULL,
  attempts integer NOT NULL DEFAULT 0
);

CREATE INDEX erasure_items_erasure ON transgate_jobs.erasure_items (erasure_id, seq);

-- A fixed window per key, shared by every replica. The key is stored only as
-- a name-based UUID of the caller's key (an address or an account).
CREATE TABLE transgate_jobs.rate_windows (
  key_hash uuid PRIMARY KEY,
  window_start_us bigint NOT NULL,
  reset_at_us bigint NOT NULL,
  hits integer NOT NULL
);

REVOKE ALL ON SCHEMA transgate_jobs FROM PUBLIC;
GRANT USAGE ON SCHEMA transgate_jobs TO billing_runtime;
GRANT EXECUTE ON FUNCTION transgate_jobs.us_to_ts(bigint), transgate_jobs.ts_to_us(timestamptz) TO billing_runtime;

GRANT SELECT, INSERT, DELETE ON transgate_jobs.jobs TO billing_runtime;
GRANT UPDATE (revision, status, job_name, source, language, translate_to, speakers, fix_grammer, duration_minutes,
              size_bytes, provider, model, callback_url, whisper_params, error, retry_count, recovery_attempts,
              soniox_transcription_id, started_at, updated_at, current_attempt, attempts_made, deferred_charge,
              next_dispatch_at)
  ON transgate_jobs.jobs TO billing_runtime;

GRANT SELECT, INSERT, DELETE ON transgate_jobs.attempts TO billing_runtime;
GRANT UPDATE (state, lease_until, remote_id, accepted_at, last_error, remote_cleanup)
  ON transgate_jobs.attempts TO billing_runtime;

-- D7: line edits update text and speaker only; they never insert.
GRANT SELECT, INSERT, DELETE ON transgate_jobs.lines TO billing_runtime;
GRANT UPDATE (line, speaker) ON transgate_jobs.lines TO billing_runtime;

GRANT SELECT, INSERT, DELETE ON transgate_jobs.inbox TO billing_runtime;
GRANT UPDATE (observation, state, settled_at, note, failures, last_error) ON transgate_jobs.inbox TO billing_runtime;

GRANT SELECT, INSERT, DELETE ON transgate_jobs.events TO billing_runtime;
GRANT UPDATE (attempts, claim_token, claimed_until, published_at, last_error) ON transgate_jobs.events TO billing_runtime;

GRANT SELECT, DELETE ON transgate_jobs.settings TO billing_runtime;
GRANT INSERT (account_id, auto_delete_transcripts, deleted_monthly) ON transgate_jobs.settings TO billing_runtime;
GRANT UPDATE (auto_delete_transcripts, deleted_monthly) ON transgate_jobs.settings TO billing_runtime;

GRANT SELECT, INSERT ON transgate_jobs.retention_runs TO billing_runtime;
GRANT UPDATE (rows_deleted, execution_time_ms, status, error_message, users_opted_out_count)
  ON transgate_jobs.retention_runs TO billing_runtime;

GRANT SELECT, INSERT, DELETE ON transgate_jobs.issued_uploads, transgate_jobs.archived_payloads TO billing_runtime;

GRANT SELECT, INSERT ON transgate_jobs.erasures TO billing_runtime;
GRANT UPDATE (state, local_erased_at, identity_deleted_at, closed_at) ON transgate_jobs.erasures TO billing_runtime;

-- Completed items drop their target details at closure (D9).
GRANT SELECT, INSERT, DELETE ON transgate_jobs.erasure_items TO billing_runtime;
GRANT UPDATE (state, attempts) ON transgate_jobs.erasure_items TO billing_runtime;

GRANT SELECT, INSERT ON transgate_jobs.rate_windows TO billing_runtime;
GRANT UPDATE (window_start_us, reset_at_us, hits) ON transgate_jobs.rate_windows TO billing_runtime;
