def rust_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def main() -> None:
    languages = json.loads((FIXTURES / "transcription-languages.json").read_text())
    targets = {row["code"] for row in json.loads((FIXTURES / "translation-targets.json").read_text())}
    locales = json.loads((FIXTURES / "ui-locales.json").read_text())

    out = [
        "// @generated by transgate/core/scripts/gen_languages.py from transgate/fixtures/languages.",
        "// Do not edit by hand; regenerate and let languages::tests check the superset.",
        "",
        "use super::{LanguageEntry, UiLocale};",
        "",
        f"pub const LANGUAGES: [LanguageEntry; {len(languages)}] = [",
    ]
    for row in languages:
        providers = {p["provider"] for p in row["providers"]}
        out.append(
            "    LanguageEntry {{ name: {name}, code: {code}, soniox: {soniox}, deepgram: {deepgram}, "
            "translation: {translation}, flag: {flag} }},".format(
                name=rust_str(row["name"]),
                code=rust_str(row["code"]),
                soniox=str("soniox" in providers).lower(),
                deepgram=str("deepgram" in providers).lower(),
                translation=str(row["code"] in targets).lower(),
                flag=rust_str(FLAGS.get(row["name"], "🌐")),
            )
        )
    out.append("];")
    out.append("")
    out.append(f"pub const UI_LOCALES: [UiLocale; {len(locales)}] = [")
    for row in locales:
        out.append(
            "    UiLocale {{ code: {code}, name: {name}, default: {default} }},".format(
                code=rust_str(row["code"]), name=rust_str(row["name"]), default=str(row["default"]).lower()
            )
        )
    out.append("];")
    OUT.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
