-- Billing schema. History lives in billing._sqlx_migrations, created by the
-- billing migrator; the host's own migration history is never touched.
--
-- No business triggers and no business functions: rules live in billing-core.
-- The two helper functions below only convert between microsecond integers and
-- timestamptz, exactly and independent of the session time zone.

CREATE SCHEMA IF NOT EXISTS billing;

CREATE FUNCTION billing.us_to_ts(us bigint) RETURNS timestamptz
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT timestamptz 'epoch'
       + (us / 1000000) * interval '1 second'
       + (us % 1000000) * interval '1 microsecond'
$$;

CREATE FUNCTION billing.ts_to_us(ts timestamptz) RETURNS bigint
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT (extract(epoch FROM ts) * 1000000)::bigint
$$;

CREATE TABLE billing.accounts (
  account_id uuid PRIMARY KEY,
  -- The trusted signup instant. The free trial is anchored here.
  created_at timestamptz NOT NULL,
  -- The only column the runtime role may update: it lets SELECT ... FOR UPDATE
  -- serialize an account without granting write access to created_at.
  touched_at timestamptz
);

CREATE TABLE billing.payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id uuid NOT NULL REFERENCES billing.accounts (account_id) ON DELETE CASCADE,
  -- The quote. Verified provider amounts are kept apart in `observed`.
  amount numeric NOT NULL,
  -- Free text: historical rows hold values new commands never accept.
  currency text NOT NULL,
  payment_gateway text NOT NULL,
  environment text NOT NULL DEFAULT 'live',
  status text NOT NULL CHECK (status IN ('pending', 'completed', 'failed', 'canceled')),
  token text,
  created timestamptz NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  coupon_id text,
  pricing_plan_id text,
  customer_id text,
  subscription_ref text,
  provider_order_ref text,
  subscription_canceled_at timestamptz,
  observed jsonb,
  receipt_url text,
  UNIQUE (account_id, id)
);

-- One provider identity, one payment: the database backstop against a second grant.
CREATE UNIQUE INDEX payments_provider_token
  ON billing.payments (payment_gateway, environment, token) WHERE token IS NOT NULL;
CREATE UNIQUE INDEX payments_provider_order
  ON billing.payments (payment_gateway, environment, provider_order_ref) WHERE provider_order_ref IS NOT NULL;
CREATE INDEX payments_account ON billing.payments (account_id, status, created DESC);

CREATE TABLE billing.packages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id uuid NOT NULL REFERENCES billing.accounts (account_id) ON DELETE CASCADE,
  payment_id bigint,
  payment_seq integer,
  -- True only for the one signup grant the runtime writes.
  signup_grant boolean NOT NULL DEFAULT false,
  name text,
  minutes_included integer NOT NULL,
  created timestamptz NOT NULL,
  start_at timestamptz NOT NULL,
  end_at timestamptz NOT NULL,
  UNIQUE (id, account_id),
  -- A package can only point at a payment of its own account.
  FOREIGN KEY (account_id, payment_id) REFERENCES billing.payments (account_id, id)
);

CREATE UNIQUE INDEX packages_payment_sequence
  ON billing.packages (payment_id, payment_seq) WHERE payment_id IS NOT NULL;
CREATE UNIQUE INDEX packages_one_signup_grant
  ON billing.packages (account_id) WHERE signup_grant;
CREATE INDEX packages_account_end ON billing.packages (account_id, end_at);

-- Runtime ledger. A zero row is the captured first-job bypass; a negative row
-- is never legitimate here.
CREATE TABLE billing.usage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id uuid NOT NULL,
  package_id bigint NOT NULL,
  subject_ref bigint,
  minutes integer NOT NULL CHECK (minutes >= 0),
  used_at timestamptz NOT NULL,
  -- A usage row can only draw on a package of its own account.
  FOREIGN KEY (package_id, account_id) REFERENCES billing.packages (id, account_id) ON DELETE CASCADE
);

CREATE INDEX usage_package ON billing.usage (package_id);
CREATE INDEX usage_account_subject ON billing.usage (account_id, subject_ref);

-- Historical ledger rows that violate the runtime invariants (cross-account
-- references, zero or negative minutes, nulls), preserved exactly as imported.
-- Only the import role can write here. Balances count them by referenced package.
CREATE TABLE billing.legacy_usage (
  id bigint PRIMARY KEY,
  account_id uuid,
  package_id bigint,
  subject_ref bigint,
  minutes integer,
  used_at timestamptz,
  imported_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX legacy_usage_package ON billing.legacy_usage (package_id);

-- The trusted binding made by an initial subscription confirmation.
CREATE TABLE billing.subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id uuid NOT NULL REFERENCES billing.accounts (account_id) ON DELETE CASCADE,
  payment_gateway text NOT NULL,
  environment text NOT NULL,
  subscription_ref text NOT NULL,
  customer_ref text,
  pricing_plan_id text,
  currency text NOT NULL,
  amount numeric NOT NULL,
  spec jsonb NOT NULL,
  initial_payment_id bigint NOT NULL,
  -- Set once, by an admin, after the provider's own detail lists the order.
  first_order_ref text,
  first_order_resolved_by text,
  first_order_rationale text,
  created_at timestamptz NOT NULL,
  cancel_requested_at timestamptz,
  UNIQUE (payment_gateway, environment, subscription_ref),
  -- A binding can only point at an initial payment of its own account.
  FOREIGN KEY (account_id, initial_payment_id) REFERENCES billing.payments (account_id, id)
);

-- Verified provider notifications that cannot be applied yet. Durable first,
-- acknowledged to the provider afterwards. `payment_id` is not a foreign key:
-- a notification may name a payment that does not exist.
CREATE TABLE billing.unresolved_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_gateway text NOT NULL,
  environment text NOT NULL,
  event_type text NOT NULL,
  subscription_ref text,
  order_ref text,
  customer_ref text,
  payment_id bigint,
  reason text NOT NULL,
  payload jsonb NOT NULL,
  received_at timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'held',
  resolved_at timestamptz,
  resolved_payment_id bigint
);

-- A held notification is identified by what it claims, so conflicting evidence is
-- a distinct row while an exact retry is the same row. The reason can change.
CREATE UNIQUE INDEX unresolved_identity ON billing.unresolved_notifications
  (payment_gateway, environment, event_type, COALESCE(order_ref, ''), COALESCE(subscription_ref, ''),
   COALESCE(customer_ref, ''), COALESCE(payment_id, -1));

CREATE TABLE billing.coupons (
  id text PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  -- real, as imported: read back through its shortest decimal text.
  amount real,
  discount_type text,
  expires_at timestamptz,
  filter jsonb
);

CREATE TABLE billing.billing_info (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  account_id uuid REFERENCES billing.accounts (account_id) ON DELETE SET NULL,
  parasut_contact_id text,
  address text,
  company_name text,
  country text,
  full_name text,
  tax_id text
);

CREATE INDEX billing_info_account ON billing.billing_info (account_id, created_at DESC);

CREATE TABLE billing.outbox (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  event_id uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  account_id uuid,
  kind text NOT NULL,
  payload jsonb NOT NULL,
  occurred_at timestamptz NOT NULL,
  attempts integer NOT NULL DEFAULT 0,
  claimed_until timestamptz,
  claim_token uuid,
  retry_after timestamptz,
  last_error text,
  published_at timestamptz
);

CREATE INDEX outbox_pending ON billing.outbox (id) WHERE published_at IS NULL;

-- Per-recipient delivery marks: a retry after a partial failure skips what was sent.
CREATE TABLE billing.outbox_deliveries (
  event_id uuid NOT NULL REFERENCES billing.outbox (event_id),
  target text NOT NULL,
  delivered_at timestamptz NOT NULL,
  PRIMARY KEY (event_id, target)
);

-- Roles. billing_runtime is what a running server must act as; billing_import
-- is the migration authority for historical data. Neither can log in. A login
-- role joins billing_runtime (see billing_postgres::provision_runtime_login).
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'billing_runtime') THEN
    CREATE ROLE billing_runtime NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'billing_import') THEN
    CREATE ROLE billing_import NOLOGIN;
  END IF;
END
$$;

REVOKE ALL ON SCHEMA billing FROM PUBLIC;
GRANT USAGE ON SCHEMA billing TO billing_runtime, billing_import;
GRANT EXECUTE ON FUNCTION billing.us_to_ts(bigint), billing.ts_to_us(timestamptz)
  TO billing_runtime, billing_import;

-- Runtime: read everything (the balance counts legacy rows too), write the
-- live tables, append to the ledger and delete a subject's rows on hard delete.
-- No UPDATE on the ledger, packages or accounts' created_at, no write at all
-- to legacy_usage, coupons or billing_info.
GRANT SELECT ON ALL TABLES IN SCHEMA billing TO billing_runtime;
GRANT INSERT ON billing.accounts, billing.packages, billing.outbox_deliveries TO billing_runtime;
GRANT UPDATE (touched_at) ON billing.accounts TO billing_runtime;
GRANT INSERT, UPDATE ON billing.subscriptions, billing.unresolved_notifications, billing.outbox TO billing_runtime;
-- Payments: the runtime may insert a payment and move its status and provider fields,
-- but never rewrite its account, quote, currency or creation time.
GRANT INSERT (account_id, amount, currency, payment_gateway, environment, status, token, created, metadata,
  coupon_id, pricing_plan_id, customer_id, subscription_ref, provider_order_ref) ON billing.payments TO billing_runtime;
GRANT UPDATE (status, token, customer_id, subscription_ref, provider_order_ref, subscription_canceled_at,
  observed, receipt_url) ON billing.payments TO billing_runtime;
GRANT DELETE ON billing.legacy_usage TO billing_runtime;
GRANT INSERT, DELETE ON billing.usage TO billing_runtime;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA billing TO billing_runtime;

GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA billing TO billing_import;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA billing TO billing_import;
